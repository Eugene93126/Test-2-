# Note frequencies (A4 = 440).
def hz(name):
    names = {'C': -9, 'C#': -8, 'Db': -8, 'D': -7, 'D#': -6, 'Eb': -6, 'E': -5, 'F': -4, 'F#': -3, 'Gb': -3, 'G': -2, 'G#': -1, 'Ab': -1, 'A': 0, 'A#': 1, 'Bb': 1, 'B': 2}
    n, o = name[:-1], int(name[-1])
    return 440.0 * 2 ** ((names[n] + 12 * (o - 4)) / 12)


# ---------- building blocks ----------

def T(sec):
    return np.arange(int(round(sec * SR))) / SR


def stereo():
    return np.zeros((N, 2))


def place(buf, sig, t0, pan=0.0, gain=1.0):
    """Add a mono or stereo signal into buf at t0 seconds, equal-power pan -1..1."""
    i0 = int(round(t0 * SR))
    if sig.ndim == 1:
        a = (pan + 1) * np.pi / 4
        sig = np.stack([sig * np.cos(a), sig * np.sin(a)], axis=1)
    j0, j1 = max(0, i0), min(N, i0 + len(sig))
    if j1 > j0:
        buf[j0:j1] += sig[j0 - i0:j1 - i0] * gain


def sos(kind, f, order=4):
    return butter(order, f, kind, fs=SR, output='sos')


def lp(x, f, o=4): return sosfilt(sos('lowpass', f, o), x, axis=0)
def hp(x, f, o=4): return sosfilt(sos('highpass', f, o), x, axis=0)
def bp(x, lo, hi, o=4): return sosfilt(sos('bandpass', [lo, hi], o), x, axis=0)


def noise(sec):
    return rng.standard_normal(int(round(sec * SR)))


def env_ar(n, a, r, shape=1.0):
    """Attack/release envelope over n samples (a, r in seconds)."""
    t = np.arange(n) / SR
    e = np.minimum(1, t / max(a, 1e-4)) * np.minimum(1, (n / SR - t) / max(r, 1e-4))
    return np.clip(e, 0, 1) ** shape


def smoother(x):
    x = np.clip(x, 0, 1)
    return x * x * x * (x * (x * 6 - 15) + 10)


def tv_filter(x, gain_fn, nper=2048):
    """Time-varying spectral shaping: gain_fn(t[1,frames], f[bins,1]) -> gains."""
    f, tt, Z = stft(x, fs=SR, nperseg=nper, noverlap=nper * 3 // 4)
    G = gain_fn(tt[None, :], f[:, None])
    _, y = istft(Z * G, fs=SR, nperseg=nper, noverlap=nper * 3 // 4)
    out = np.zeros_like(x)
    out[:min(len(x), len(y))] = y[:len(x)]
    return out


def ir(sec, decay, lowcut=8000, seed=1):
    """A synthetic stereo room: decorrelated decaying noise, darker as it fades."""
    r = np.random.default_rng(seed)
    t = T(sec)
    out = []
    for ch in range(2):
        n = r.standard_normal(len(t)) * np.exp(-t / decay)
        n = lp(n, lowcut, 2)
        n[: int(0.012 * SR)] *= np.linspace(0, 1, int(0.012 * SR))
        out.append(n)
    h = np.stack(out, axis=1)
    return h / np.sqrt((h ** 2).sum(axis=0).mean())


def reverb(x, h, wet=0.3):
    """x: (n,2) -> x + wet * (x conv h), length extended by the tail."""
    y = np.stack([fftconvolve(x[:, c], h[:, c]) for c in range(2)], axis=1)
    out = np.zeros_like(y)
    out[:len(x)] = x
    return out + wet * y


def sine_sweep(sec, f0, f1, curve='exp'):
    t = T(sec)
    k = t / sec
    f = f0 * (f1 / f0) ** k if curve == 'exp' else f0 + (f1 - f0) * k
    return np.sin(2 * np.pi * np.cumsum(f) / SR)


