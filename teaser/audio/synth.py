# Paper settling, faint.
def rustle(sec, density=60, lo=1500, hi=9000):
    n = int(round(sec * SR))
    out = np.zeros(n)
    k = int(density * sec)
    for _ in range(k):
        i = rng.integers(0, max(1, n - 800))
        L = rng.integers(80, 700)
        out[i:i + L] += rng.standard_normal(L) * np.exp(-np.arange(L) / (L / 4)) * rng.uniform(0.3, 1)
    return bp(out + 0.15 * rng.standard_normal(n), lo, hi, 2)


