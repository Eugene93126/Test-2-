# 18.8: one low piano-like D3, long room.
def piano(f0, sec=1.25):
    t = T(sec)
    B = 0.00035
    out = np.zeros(len(t))
    for n in range(1, 18):
        fn = n * f0 * np.sqrt(1 + B * n * n)
        amp = (1 / n ** 1.15) * (1 if n < 8 else 0.6)
        d1, d2 = 0.18 / (1 + 0.25 * n), 2.2 / (1 + 0.3 * n)
        e = 0.55 * np.exp(-t / d1) + 0.45 * np.exp(-t / d2)
        for c in (-0.35, 0.0, 0.35):  # three strings, a few cents apart
            out += amp * e * np.sin(2 * np.pi * fn * 2 ** (c / 1200) * t + rng.random() * 6.28) / 3
    hammer = lp(noise(sec), 2500, 2) * np.exp(-t / 0.006) * 0.4
    return (out + hammer) * env_ar(len(t), 0.002, 0.12)


