"""Pantheon 2.0 teaser: score and sound design, synthesised from scratch.

Every sound here is generated by this file with numpy/scipy (no samples, no
recordings), timed from src/timeline.json, the same file the picture reads.

    python3 audio/synth.py            # writes out/audio/{music,sfx,mix}.wav

Mix: -14 LUFS integrated, true peak <= -1 dBTP (4x oversampled), 48 kHz 24-bit.
Stems are written at the mix gain, before the final peak limiter.
"""
