place(sfx, hp(noise(0.006), 2000, 2), flare + 0.008, 0, 0.25)  # the contact's second bounce


# ---------- rules, mix, loudness ----------

def cut_after(x, t_cut):
    """Nothing rings past the cut: hard gate with a 1 ms fade."""
    i = int(round(t_cut * SR))
    f = int(0.001 * SR)
    x[i - f:i] *= np.linspace(1, 0, f)[:, None]
    x[i:] = 0
    return x


black0, black1 = EV['black']
music = cut_after(music, black0)
sfx = cut_after(sfx, black0)
music += final_note
music[int(round(black0 * SR)):int(round(black1 * SR))] = 0
sfx[int(round(black0 * SR)):int(round(black1 * SR))] = 0

SFX_OVER_MUSIC_DB = 2.5
sfx *= 10 ** (SFX_OVER_MUSIC_DB / 20)
mix = music + sfx
music = hp(music, 20, 2)
sfx = hp(sfx, 20, 2)
mix = music + sfx

meter = pyln.Meter(SR)
gain_db = TL['audio']['loudness']['integratedLUFS'] - meter.integrated_loudness(mix)
for _ in range(4):
    # Normalise, limit the true peak, re-measure (the limiter costs a little loudness).
    g = 10 ** (gain_db / 20)
    m = mix * g
    ceiling = 10 ** (TL['audio']['loudness']['truePeakDBTP'] / 20) * 0.94
    over = np.abs(resample_poly(m, 4, 1, axis=0)).max(axis=1)
    over = np.maximum(over.reshape(-1, 4).max(axis=1), 1e-9)
    gr = np.minimum(1, ceiling / over)
    # Look-ahead: 1.5 ms attack, 60 ms release, so the limiter never clicks.
    la = int(0.0015 * SR)
    gr = np.lib.stride_tricks.sliding_window_view(np.pad(gr, (0, la), constant_values=1), la + 1).min(axis=1)
    rel = np.exp(-1 / (0.06 * SR))
    sm = np.empty_like(gr)
    cur = 1.0
    for i, v in enumerate(gr):
        cur = v if v < cur else v + (cur - v) * rel
        sm[i] = cur
    limited = m * sm[:, None]
    lufs = meter.integrated_loudness(limited)
    if abs(lufs - TL['audio']['loudness']['integratedLUFS']) < 0.1:
        break
    gain_db += TL['audio']['loudness']['integratedLUFS'] - lufs

tp = 20 * np.log10(np.abs(resample_poly(limited, 4, 1, axis=0)).max())
g = 10 ** (gain_db / 20)
# Re-impose the silences exactly (true digital zeros).
for buf in (limited,):
    buf[int(round(black0 * SR)):int(round(black1 * SR))] = 0

