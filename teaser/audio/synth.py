# Grippers and servos: short whirs as the arms move.
def whir(sec, f0, f1, level=1.0):
    t = T(sec)
    f = f0 + (f1 - f0) * smoother(t / sec)
    ph = 2 * np.pi * np.cumsum(f) / SR
    s = 0.6 * np.sin(ph) + 0.25 * np.sin(2 * ph) + 0.15 * np.sin(3.01 * ph)
    s = lp(s + 0.05 * rng.standard_normal(len(t)), 1800, 2)
    return s * env_ar(len(t), 0.04, 0.08) * level


