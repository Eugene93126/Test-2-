def glass_note(f, dec=0.35):
    t = T(1.2)
    mod = np.sin(2 * np.pi * f * 3.5 * t) * 1.2 * np.exp(-t / 0.08)
    s = np.sin(2 * np.pi * f * t + mod) * np.exp(-t / dec) + 0.3 * np.sin(2 * np.pi * f * 2 * t) * np.exp(-t / (dec * 0.5))
    return s * env_ar(len(t), 0.003, 0.05)


